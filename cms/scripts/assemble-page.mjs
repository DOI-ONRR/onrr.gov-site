#!/usr/bin/env node
/**
 * assemble-page.mjs — emit SQL that creates a NEW page wired to EXISTING block items.
 *
 * Reads a migrate-page.mjs dump (the jsonb_populate_record .sql) purely for its STRUCTURE:
 * the pages row (field values to clone) and the pages_page_blocks rows (which top-level
 * blocks the page points at, and in what order). It then emits SQL that, run against a DB
 * where those block items ALREADY EXIST (e.g. upgrade), creates one new page and the
 * top-level pages_page_blocks junctions pointing at the existing items — WITHOUT inserting
 * any item rows. Nested junctions (tab_blocks_tab_blocks, expansion_panels_...) are assumed
 * to already exist in the target and are left untouched (scope: top-level page_blocks only).
 *
 * The new page gets a fresh UUID and collision-safe defaults (slug/url '-copy', title
 * '(copy)', status 'draft'); review and edit those in the output before importing. The SQL
 * aborts up front if any referenced top-level block item is missing in the target.
 *
 * Usage:
 *   node scripts/assemble-page.mjs page.sql > new-page.sql
 *   # optional overrides: NEW_SLUG= NEW_URL= NEW_TITLE= NEW_STATUS= NEW_PARENT= NEW_PAGE_ID=
 * Then import over an open tunnel (see migrate-page.mjs header):
 *   psql "postgres://USER:PASS@127.0.0.1:5433/DB?sslmode=require" -v ON_ERROR_STOP=1 -f new-page.sql
 */
import { readFileSync } from 'node:fs';
import { randomUUID } from 'node:crypto';

const dumpPath = process.argv[2];
if (!dumpPath) { console.error('usage: node scripts/assemble-page.mjs page.sql > new-page.sql'); process.exit(2); }
const sql = readFileSync(dumpPath, 'utf8');
const log = (...a) => console.error(...a);           // diagnostics → stderr (stdout is the SQL)
const out = (s) => process.stdout.write(s + '\n');

// Decode a Postgres string-literal body back to its text ('' → ', and \\ → \ in E'' form).
function decodeLiteral(s, isE) {
  let r = '';
  for (let i = 0; i < s.length; i++) {
    if (s[i] === "'" && s[i + 1] === "'") { r += "'"; i++; continue; }
    if (isE && s[i] === '\\' && s[i + 1] === '\\') { r += '\\'; i++; continue; }
    r += s[i];
  }
  return r;
}

// Encode a text value as a Postgres string literal (inverse of decodeLiteral): double every
// ' and, when backslashes are present, use the E'' form and double every \ too.
function lit(v) {
  const t = String(v);
  return t.includes('\\')
    ? `E'${t.replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
    : `'${t.replace(/'/g, "''")}'`;
}

// --- parse the dump (one INSERT per line) ---------------------------------------
const byTable = new Map();
const openRe = /jsonb_populate_record\(NULL::"([^"]+)", (E?)'/;
for (const line of sql.split('\n')) {
  if (!line.startsWith('INSERT INTO')) continue;
  const m = line.match(openRe);
  const end = line.lastIndexOf("'::jsonb)");
  if (!m || end < 0) continue;
  const body = decodeLiteral(line.slice(m.index + m[0].length, end), m[2] === 'E');
  let row;
  try { row = JSON.parse(body); } catch (e) { log(`parse fail ${m[1]}: ${e.message}`); continue; }
  (byTable.get(m[1]) ?? byTable.set(m[1], []).get(m[1])).push(row);
}

const page = byTable.get('pages')?.[0];
if (!page) { log('error: no pages row found in the dump'); process.exit(1); }
const topBlocks = (byTable.get('pages_page_blocks') || []).slice().sort((a, b) => (+a.sort || 0) - (+b.sort || 0));
if (!topBlocks.length) { log('error: no pages_page_blocks rows found in the dump'); process.exit(1); }

// --- new page identity (env overrides, else collision-safe defaults) ------------
const newId = process.env.NEW_PAGE_ID || randomUUID();
const newSlug = process.env.NEW_SLUG || `${page.slug}-copy`;
const newUrl = process.env.NEW_URL || (page.url ? page.url.replace(/[^/]*$/, newSlug) : null);
const newTitle = process.env.NEW_TITLE || `${page.title} (copy)`;
const newStatus = process.env.NEW_STATUS || 'draft';
const newParent = process.env.NEW_PARENT ?? page.parent;
const newPage = { ...page, id: newId, slug: newSlug, url: newUrl, title: newTitle, status: newStatus, parent: newParent };

// --- emit -----------------------------------------------------------------------
out('-- Generated by assemble-page.mjs');
out(`-- source dump: ${dumpPath}`);
out(`-- new page id: ${newId}`);
out('-- Creates a NEW page wired to EXISTING top-level block items. No item rows are created.');
out('-- Nested junctions (tabs/panels -> children) are assumed to already exist in the target.');
out('--');
out('-- >>> REVIEW/EDIT in the pages insert below before importing: title, slug, url, parent, status.');
out(`--     original: slug=${page.slug} url=${page.url} title=${JSON.stringify(page.title)} status=${page.status} parent=${page.parent}`);
out(`--     new:      slug=${newSlug} url=${newUrl} title=${JSON.stringify(newTitle)} status=${newStatus} parent=${newParent}`);
out('');
out('BEGIN;');
out('SET LOCAL session_replication_role = replica;  -- bypass FK checks + pages url/order triggers');
out('');

out('-- 1) Abort if any referenced top-level block item is missing in this database.');
out('DO $$');
out("DECLARE r record; ok boolean; missing text := '';");
out('BEGIN');
out('  FOR r IN SELECT * FROM (VALUES');
out(topBlocks.map((j) => `    (${lit(j.collection)}, ${lit(j.item)})`).join(',\n'));
out('  ) AS t(coll, item) LOOP');
out("    EXECUTE format('SELECT EXISTS(SELECT 1 FROM %I WHERE id = $1)', r.coll) INTO ok USING r.item::uuid;");
out("    IF NOT ok THEN missing := missing || r.coll || ':' || r.item || ' '; END IF;");
out('  END LOOP;');
out("  IF missing <> '' THEN RAISE EXCEPTION 'missing referenced block items: %', missing; END IF;");
out('END $$;');
out('');

out('-- 2) The new page (fresh id; edit the marked fields above as needed).');
out(`INSERT INTO "pages" SELECT * FROM jsonb_populate_record(NULL::"pages", ${lit(JSON.stringify(newPage))}::jsonb) ON CONFLICT (id) DO NOTHING;`);
out('');

out('-- 3) Wire the new page to the existing top-level blocks (fresh junction ids, sort preserved).');
for (const j of topBlocks)
  out(`INSERT INTO "pages_page_blocks" ("id", "pages_id", "item", "collection", "sort") VALUES (${lit(randomUUID())}, ${lit(newId)}, ${lit(j.item)}, ${lit(j.collection)}, ${Number(j.sort) || 0});`);
out('');
out('SET LOCAL session_replication_role = origin;');
out('COMMIT;');

log(`\nNew page: ${newTitle}  (${newId})`);
log(`  slug: ${newSlug}   url: ${newUrl}   parent: ${newParent} (ensure it exists in the target)`);
log(`  top-level page blocks wired: ${topBlocks.length}`);
for (const j of topBlocks) log(`   - ${j.collection}:${j.item} (sort ${j.sort})`);
